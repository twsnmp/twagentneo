//go:build darwin

package network

import (
	"fmt"
	"net"
	"syscall"

	"golang.org/x/net/route"
)

const (
	rtfLLInfo = 0x400 // RTF_LLINFO: generated by link layer (ARP/NDP)
	rtfStatic = 0x800 // RTF_STATIC: manually added
)

// getARP retrieves ARP and NDP neighbor cache entries on macOS via route RIB.
func getARP() ([]ARPEntry, error) {
	// Fetch routing information base with RTF_LLINFO flag (link-layer / ARP cache entries).
	rib, err := route.FetchRIB(syscall.AF_UNSPEC, route.RIBType(syscall.NET_RT_FLAGS), rtfLLInfo)
	if err != nil {
		return nil, fmt.Errorf("route FetchRIB: %w", err)
	}

	msgs, err := route.ParseRIB(route.RIBType(syscall.NET_RT_FLAGS), rib)
	if err != nil {
		return nil, fmt.Errorf("route ParseRIB: %w", err)
	}

	ifaces, _ := net.Interfaces()
	ifaceMap := make(map[int]string, len(ifaces))
	for _, iface := range ifaces {
		ifaceMap[iface.Index] = iface.Name
	}

	var entries []ARPEntry
	for _, m := range msgs {
		rm, ok := m.(*route.RouteMessage)
		if !ok {
			continue
		}

		var ip, mac string
		if len(rm.Addrs) > syscall.RTAX_DST && rm.Addrs[syscall.RTAX_DST] != nil {
			switch a := rm.Addrs[syscall.RTAX_DST].(type) {
			case *route.Inet4Addr:
				ip = net.IPv4(a.IP[0], a.IP[1], a.IP[2], a.IP[3]).String()
			case *route.Inet6Addr:
				ip = net.IP(a.IP[:]).String()
			}
		}

		if len(rm.Addrs) > syscall.RTAX_GATEWAY && rm.Addrs[syscall.RTAX_GATEWAY] != nil {
			if a, ok := rm.Addrs[syscall.RTAX_GATEWAY].(*route.LinkAddr); ok && len(a.Addr) == 6 {
				mac = fmt.Sprintf("%02x:%02x:%02x:%02x:%02x:%02x",
					a.Addr[0], a.Addr[1], a.Addr[2], a.Addr[3], a.Addr[4], a.Addr[5])
			}
		}

		if ip == "" || mac == "" {
			continue
		}

		entryType := "dynamic"
		if rm.Flags&rtfStatic != 0 {
			entryType = "static"
		}

		entries = append(entries, ARPEntry{
			IP:        ip,
			MAC:       mac,
			Interface: ifaceMap[rm.Index],
			Type:      entryType,
		})
	}

	return entries, nil
}
